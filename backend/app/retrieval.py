def build_knowledge_index(
    root: Path,
    *,
    index_dir: Path | None = None,
    embedding_provider: EmbeddingProvider | Callable[[Sequence[str]], Sequence[Sequence[float]]] | None = None,
    force: bool = False,
    **kwargs: Any,
) -> PersistentHybridIndex:
    """Create and build an index in one call.

    This convenience function is useful from a FastAPI lifespan hook or a
    command-line rebuild script::

        index = build_knowledge_index(settings.knowledge_path,
                                      index_dir=settings.project_root / ".retrieval_index")

    The returned object remains searchable and exposes ``stats()`` for health
    reporting.  ``kwargs`` are forwarded to :class:`PersistentHybridIndex`.
    """

    index = PersistentHybridIndex(
        root,
        index_dir=index_dir,
        embedding_provider=embedding_provider,
        **kwargs,
    )
    index.build(force=force)
    return index


