"""Document ingestion and hybrid retrieval for the support knowledge base.

The application intentionally has no mandatory vector-database dependency.  This
module provides a durable, deterministic local index (sparse TF-IDF + keyword
matching) and an optional dense-vector layer.  A remote or local embedding model
can be plugged in through :class:`EmbeddingProvider`; the built-in
``HashEmbeddingProvider`` keeps the demo useful when no model package is
installed.

The public API is deliberately small::

    index = PersistentHybridIndex(Path("data"))
    index.rebuild()                 # or ``index.build()`` for incremental use
    hits = index.search("滚刷缠绕怎么办", top_k=5)
    context, citations = index.context("滚刷缠绕怎么办")

Every hit carries a stable chunk id and citation metadata (source file, page,
chunk number and character offsets), so generated answers can be audited.
Index files are JSON and are written atomically.  They are runtime artifacts;
callers can put ``index_dir`` in ``.gitignore`` rather than committing them.
"""

